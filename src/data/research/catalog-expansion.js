/**
 * Gibt detaillierte Statistiken über den gesamten Recherchebestand zurück
 */
export function getResearchCatalogStats() {
  const byManufacturer = {};
  const byType = {};
  const byStatus = {};
  const byEntityType = {};

  RESEARCH_CATALOG.forEach(item => {
    byManufacturer[item.manufacturer] = (byManufacturer[item.manufacturer] || 0) + 1;
    byType[item.lens_type] = (byType[item.lens_type] || 0) + 1;
    byStatus[item.pipeline_status] = (byStatus[item.pipeline_status] || 0) + 1;
    byEntityType[item.entity_type] = (byEntityType[item.entity_type] || 0) + 1;
  });

  return {
    total_researched: RESEARCH_CATALOG.length,
    by_manufacturer: byManufacturer,
    by_type: byType,
    by_status: byStatus,
    by_entity_type: byEntityType,
    verified_sources_count: RESEARCH_CATALOG.filter(i => i.pipeline_status === 'SOURCE_IDENTIFIED').length
  };
}
