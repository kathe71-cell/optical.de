export const getProductsByCategory = (category) => {
  if (!category || category === 'all') return PRODUCTS;
  return PRODUCTS.filter((p) => {
    if (category === 'monat') return p.lens_type.toLowerCase().includes('monatslinse') && !p.lens_type.toLowerCase().includes('torisch') && !p.lens_type.toLowerCase().includes('multifokal');
    if (category === 'tag') return p.lens_type.toLowerCase().includes('tageslinse') && !p.lens_type.toLowerCase().includes('torisch');
    if (category === 'toric') return p.lens_type.toLowerCase().includes('torisch');
    if (category === 'multifocal') return p.lens_type.toLowerCase().includes('multifokal');
    if (category === 'pflege') return p.lens_type.toLowerCase().includes('pflegemittel') || p.lens_type.toLowerCase().includes('augentropfen');
    return true;
  });
};

