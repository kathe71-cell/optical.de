/**
 * Dynamische Berechnung von Stück-, Tages- und Monatskosten
 * Strikte Regel: Keine Erfindungen. Bei fehlender Packungsgröße oder Pflegemitteln
 * wird transparent mitgeteilt, dass keine belastbare Berechnung möglich ist.
 */
export const calculateLensCosts = (product, usage = 'both_eyes') => {
  if (!product || !product.pack_count || !product.price || product.lens_type?.toLowerCase().includes('pflegemittel')) {
    return {
      computable: false,
      reason: 'Keine belastbare Berechnung möglich – Packungsgröße nicht hinterlegt oder Pflegemittel.',
      price_per_lens: '–',
      cost_per_day: '–',
      cost_per_month: '–'
    };
  }

  const isMonthly = product.replacement_schedule?.toLowerCase().includes('30 tage');
  const isDaily = product.replacement_schedule?.toLowerCase().includes('1 tag');
  const pricePerLensNum = product.price / product.pack_count;
  const eyesFactor = usage === 'both_eyes' ? 2 : 1;

  if (isMonthly) {
    // Packung mit N Linsen reicht für (N / eyesFactor) Monate à 30 Tage
    const monthsPerPack = product.pack_count / eyesFactor;
    const costPerMonthNum = product.price / monthsPerPack;
    const costPerDayNum = costPerMonthNum / 30;
    return {
      computable: true,
      price_per_lens: `${pricePerLensNum.toFixed(2).replace('.', ',')} €`,
      cost_per_day: `${costPerDayNum.toFixed(2).replace('.', ',')} €`,
      cost_per_month: `${costPerMonthNum.toFixed(2).replace('.', ',')} €`,
      usage_description: usage === 'both_eyes' ? 'Beidseitiges Tragen (2 Linsen / Monat)' : 'Einseitiges Tragen (1 Linse / Monat)'
    };
  }

  if (isDaily) {
    // 2 Linsen pro Tag für beide Augen
    const daysPerPack = product.pack_count / eyesFactor;
    const costPerDayNum = product.price / daysPerPack;
    const costPerMonthNum = costPerDayNum * 30;
    return {
      computable: true,
      price_per_lens: `${pricePerLensNum.toFixed(2).replace('.', ',')} €`,
      cost_per_day: `${costPerDayNum.toFixed(2).replace('.', ',')} €`,
      cost_per_month: `${costPerMonthNum.toFixed(2).replace('.', ',')} €`,
      usage_description: usage === 'both_eyes' ? 'Beidseitiges Tragen (2 Linsen / Tag)' : 'Einseitiges Tragen (1 Linse / Tag)'
    };
  }

  return {
    computable: false,
    reason: 'Berechnung nur für Tages- und Monatslinsen hinterlegt.',
    price_per_lens: `${pricePerLensNum.toFixed(2).replace('.', ',')} €`,
    cost_per_day: '–',
    cost_per_month: '–'
  };
};

export const getProductById = (id) => PRODUCTS.find((p) => p.id === id);

export const getProductsByCategory = (category) => {
  if (!category || category === 'all') return PRODUCTS;
  return PRODUCTS.filter((p) => {
    if (category === 'monat') return p.lens_type.toLowerCase().includes('monatslinse') && !p.lens_type.toLowerCase().includes('torisch') && !p.lens_type.toLowerCase().includes('multifokal');
    if (category === 'tag') return p.lens_type.toLowerCase().includes('tageslinse') && !p.lens_type.toLowerCase().includes('torisch');
    if (category === 'toric') return p.lens_type.toLowerCase().includes('torisch');
    if (category === 'multifocal') return p.lens_type.toLowerCase().includes('multifokal');
    if (category === 'pflege') return p.lens_type.toLowerCase().includes('pflegemittel') || p.lens_type.toLowerCase().includes('augentropfen');
    return true;
  });
};
